#!/usr/bin/env node
/* Disposable SQL migration validation. Never connects to hosted Supabase. */
import { randomBytes } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { readFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';

const root = fileURLToPath(new URL('../../..', import.meta.url));
const name = `codex-gemini-routes-${process.pid}-${randomBytes(4).toString('hex')}`;
const migrationPath = 'supabase/migrations/20260904150000_refresh_gemini_flash_fallback_routes.sql';

const command = (file, args, input = '') => new Promise((resolve, reject) => {
  const child = spawn(file, args, { stdio: ['pipe', 'pipe', 'pipe'] });
  let stdout = '';
  let stderr = '';
  child.stdout.on('data', chunk => { stdout += chunk; });
  child.stderr.on('data', chunk => { stderr += chunk; });
  child.on('error', reject);
  child.on('close', code => code === 0
    ? resolve(stdout)
    : reject(new Error(`${file} ${args.join(' ')} failed\n${stderr}${stdout}`)));
  child.stdin.end(input);
});

const docker = (args, input) => command('docker', args, input);
const psql = (sql) => docker([
  'exec', '-i', name, 'psql', '-X', '-v', 'ON_ERROR_STOP=1',
  '-v', 'VERBOSITY=verbose', '-U', 'postgres', '-d', 'postgres',
], sql);
const expectFailure = async (sql, message) => {
  try {
    await psql(sql);
    throw new Error(`expected migration failure containing: ${message}`);
  } catch (error) {
    if (error.message.startsWith('expected migration failure')) throw error;
    if (!error.message.includes(message)) {
      throw new Error(`expected ${message}, got ${error.message}`);
    }
  }
};

const schemaSql = `
drop schema if exists public cascade;
create schema public;
create table public.ai_model_catalog (
  id integer generated by default as identity primary key,
  provider text not null,
  model_name text not null,
  display_name text,
  free_tier_daily_request_limit integer,
  free_tier_status text not null default 'unknown',
  is_enabled boolean not null default true,
  is_free_tier_eligible boolean not null default false,
  notes text,
  supports_images boolean not null default false,
  supports_json_output boolean not null default false,
  supports_structured_output boolean not null default false,
  supports_text boolean not null default true,
  constraint ai_model_catalog_provider_model_name_key unique (provider, model_name)
);
create table public.ai_model_task_routes (
  id integer generated by default as identity primary key,
  task_type text not null,
  provider text not null,
  model_name text not null,
  route_order integer not null check (route_order > 0),
  is_enabled boolean not null default true,
  require_images boolean not null default false,
  require_json_output boolean not null default true,
  require_structured_output boolean not null default false,
  fallback_on_rate_limit boolean not null default true,
  fallback_on_quota_exceeded boolean not null default true,
  fallback_on_unavailable boolean not null default true,
  notes text,
  constraint ai_model_task_routes_task_provider_model_key unique (task_type, provider, model_name),
  constraint ai_model_task_routes_task_route_order_key unique (task_type, route_order),
  constraint ai_model_task_routes_provider_model_name_fkey foreign key (provider, model_name)
    references public.ai_model_catalog (provider, model_name)
);
create table public.app_settings (
  id text primary key,
  gemini_daily_limit integer
);
`;

const catalogSql = `
insert into public.ai_model_catalog
  (provider, model_name, display_name, free_tier_daily_request_limit,
   free_tier_status, is_enabled, is_free_tier_eligible, notes,
   supports_images, supports_json_output, supports_structured_output, supports_text)
values
  ('google', 'gemini-3.5-flash-lite', 'Gemini 3.5 Flash Lite', 500, 'confirmed', true, true, 'existing', true, true, true, true),
  ('google', 'gemini-3.1-flash-lite', 'Gemini 3.1 Flash Lite', 500, 'confirmed', true, true, 'existing', true, true, true, true),
  ('google', 'gemini-3.5-flash', 'Gemini 3.5 Flash', 20, 'confirmed', true, true, 'existing', true, true, true, true),
  ('google', 'gemini-3-flash-preview', 'Gemini 3 Flash Preview', 20, 'confirmed', true, true, 'existing', true, true, true, true),
  ('google', 'gemini-extra', 'Extra Google Route', 20, 'confirmed', true, true, 'extra', true, true, true, true),
  ('openai', 'gpt-extra', 'Unrelated Provider Route', null, 'unknown', true, false, 'unrelated', false, false, false, true)
on conflict (provider, model_name) do nothing;
`;

const routeSql = ({ collision, defaultLimit = 1040 }) => `
insert into public.ai_model_task_routes
  (task_type, provider, model_name, route_order, is_enabled,
   require_images, require_json_output, require_structured_output,
   fallback_on_rate_limit, fallback_on_quota_exceeded, fallback_on_unavailable, notes)
values
  ('listing_draft_generation', 'google', 'gemini-3.5-flash-lite', ${collision ? 10 : 1}, true, true, true, true, true, true, true, 'existing'),
  ('listing_draft_generation', 'google', 'gemini-3.1-flash-lite', ${collision ? 20 : 2}, true, true, true, true, true, true, true, 'existing'),
  ('listing_draft_generation', 'google', 'gemini-3.5-flash', ${collision ? 30 : 3}, true, true, true, true, true, true, true, 'existing'),
  ('listing_draft_generation', 'google', 'gemini-3-flash-preview', ${collision ? 40 : 4}, true, true, true, true, true, true, true, 'existing'),
  ('listing_draft_generation', 'google', 'gemini-extra', ${collision ? 50 : 50}, true, true, true, true, true, true, true, 'extra'),
  ('listing_draft_generation', 'openai', 'gpt-extra', ${collision ? 3 : 1001}, true, false, false, false, false, false, false, 'unrelated'),
  ('other_task', 'openai', 'gpt-extra', 1, true, false, false, false, false, false, false, 'other task');
insert into public.app_settings (id, gemini_daily_limit)
values ('default', ${defaultLimit === null ? 'null' : defaultLimit}), ('custom', 777), ('null-setting', null);
`;

const setup = async (options = {}) => {
  await psql(schemaSql + catalogSql + routeSql(options));
};

const migration = await readFile(`${root}/${migrationPath}`, 'utf8');

const assertCanonicalState = `
do $$
declare
  enabled_models text[];
  enabled_orders integer[];
begin
  select array_agg(model_name order by route_order)
  into enabled_models
  from public.ai_model_task_routes
  where task_type='listing_draft_generation' and provider='google' and is_enabled;
  if enabled_models is distinct from array[
    'gemini-3.5-flash-lite', 'gemini-3.1-flash-lite', 'gemini-3.8-flash',
    'gemini-3.7-flash', 'gemini-3.6-flash', 'gemini-3.5-flash'
  ] then raise exception 'unexpected enabled Google route set: %', enabled_models; end if;
  select array_agg(route_order order by route_order)
  into enabled_orders
  from public.ai_model_task_routes
  where task_type='listing_draft_generation' and provider='google' and is_enabled;
  if enabled_orders is distinct from array[1, 2, 3, 4, 5, 6]
  then raise exception 'unexpected enabled Google route orders: %', enabled_orders; end if;
  if exists (
    select 1 from public.ai_model_task_routes
    where task_type='listing_draft_generation' and provider='google'
      and route_order between 1 and 6
      and model_name <> all(array[
        'gemini-3.5-flash-lite', 'gemini-3.1-flash-lite', 'gemini-3.8-flash',
        'gemini-3.7-flash', 'gemini-3.6-flash', 'gemini-3.5-flash'
      ])
  ) then raise exception 'stale Google route occupies canonical order'; end if;
  if exists (
    select 1 from public.ai_model_task_routes
    where task_type='listing_draft_generation' and provider='google'
      and not (fallback_on_rate_limit and fallback_on_quota_exceeded and fallback_on_unavailable)
      and is_enabled
  ) then raise exception 'canonical Google fallback flags are not all enabled'; end if;
  if exists (
    select 1 from public.ai_model_task_routes
    where task_type='listing_draft_generation' and provider='google' and is_enabled
      and not (require_images and require_json_output and require_structured_output)
  ) then raise exception 'canonical Google requirement flags are not all enabled'; end if;
  if (select count(*) from public.ai_model_task_routes
      where task_type='listing_draft_generation' and provider='google' and is_enabled) <> 6
    or (select count(*) from public.ai_model_task_routes
      where task_type='listing_draft_generation' and provider='google' and model_name='gemini-3-flash-preview' and is_enabled) <> 0
    or (select count(*) from public.ai_model_task_routes
      where task_type='listing_draft_generation' and provider='google' and model_name='gemini-extra' and is_enabled) <> 0
  then raise exception 'preview or stale Google route remained enabled'; end if;
  if exists (
    select 1 from (values
      ('gemini-3.5-flash-lite', 500), ('gemini-3.1-flash-lite', 500),
      ('gemini-3.8-flash', 20), ('gemini-3.7-flash', 20),
      ('gemini-3.6-flash', 20), ('gemini-3.5-flash', 20)
    ) expected(model_name, daily_limit)
    left join public.ai_model_catalog catalog using (model_name)
    where catalog.model_name is null or catalog.provider <> 'google'
      or catalog.free_tier_daily_request_limit is distinct from expected.daily_limit
      or catalog.free_tier_status <> 'confirmed'
      or not (catalog.is_enabled and catalog.is_free_tier_eligible
        and catalog.supports_images and catalog.supports_json_output
        and catalog.supports_structured_output and catalog.supports_text)
  ) then raise exception 'catalog daily request limits are incorrect'; end if;
  if (select gemini_daily_limit from public.app_settings where id='default') <> 1080
    or (select gemini_daily_limit from public.app_settings where id='custom') <> 777
    or (select gemini_daily_limit from public.app_settings where id='null-setting') is not null
  then raise exception 'app_settings update was not narrowly scoped'; end if;
  if (select route_order from public.ai_model_task_routes where task_type='listing_draft_generation' and provider='openai' and model_name='gpt-extra') <> 1001
    or not (select is_enabled from public.ai_model_task_routes where task_type='listing_draft_generation' and provider='openai' and model_name='gpt-extra')
    or (select route_order from public.ai_model_task_routes where task_type='other_task' and provider='openai' and model_name='gpt-extra') <> 1
  then raise exception 'unrelated provider/task route changed'; end if;
  if exists (select 1 from public.ai_model_task_routes group by task_type having count(*) <> count(distinct route_order))
  then raise exception 'route_order uniqueness was not preserved'; end if;
  if exists (
    select model_name from public.ai_model_task_routes
    where task_type='listing_draft_generation' and provider='google'
    group by model_name having count(*) <> 1
  ) then raise exception 'duplicate Google route rows created'; end if;
end
$$;
`;

const snapshotRouteState = `
create table public._route_state_snapshot as
select to_jsonb(route) - 'updated_at' as state
from public.ai_model_task_routes route;
`;

const assertReplayStable = `
do $$
begin
  if exists (
    (select to_jsonb(route) - 'updated_at' as state
     from public.ai_model_task_routes route
     except
     select state from public._route_state_snapshot)
    union all
    (select state from public._route_state_snapshot
     except
     select to_jsonb(route) - 'updated_at' as state
     from public.ai_model_task_routes route)
  ) then
    raise exception 'second migration replay changed route state';
  end if;
end
$$;
`;

const assertDefaultLimit = value => `
do $$ begin
  if (select gemini_daily_limit from public.app_settings where id='default') is distinct from ${value === null ? 'null' : value}
  then raise exception 'default Gemini daily limit changed unexpectedly'; end if;
end $$;
`;

async function main() {
  await docker(['run', '-d', '--rm', '--name', name, '-e', 'POSTGRES_PASSWORD=codex-gemini-postgres', 'postgres:17-alpine']);
  try {
    for (let attempt = 0; attempt < 120; attempt += 1) {
      try {
        await psql('select 1');
        break;
      } catch (error) {
        if (attempt === 119) throw new Error(`postgres readiness timeout: ${error.message}`);
        await new Promise(resolve => setTimeout(resolve, 250));
      }
    }

    await setup();
    await psql(migration);
    await psql(assertCanonicalState);
    await psql(snapshotRouteState);
    await psql(migration);
    await psql(assertCanonicalState);
    await psql(assertReplayStable);

    await psql("update public.app_settings set gemini_daily_limit=null where id='default';");
    await psql(migration);
    await psql(assertDefaultLimit(null));
    await psql("update public.app_settings set gemini_daily_limit=777 where id='default';");
    await psql(migration);
    await psql(assertDefaultLimit(777));

    await setup({ collision: true });
    await expectFailure(migration, 'non-Google listing_draft_generation route occupies canonical order 1-6');
    await psql(`
      do $$ begin
        if (select count(*) from public.ai_model_catalog) <> 6
          or (select gemini_daily_limit from public.app_settings where id='default') <> 1040
          or (select route_order from public.ai_model_task_routes where task_type='listing_draft_generation' and provider='google' and model_name='gemini-3.5-flash-lite') <> 10
        then raise exception 'collision failure was not atomic'; end if;
      end $$;
    `);
    console.log('Gemini fallback route migration disposable validation: passed');
  } finally {
    await docker(['rm', '-f', name]).catch(() => {});
  }
}

main().catch(error => {
  console.error(error.stack || error);
  process.exitCode = 1;
});
